test('CLI executes as a Node entrypoint and persists only the external registry', () => fixture(({ base, vault, stateDir, put }) => {
  const note = put('Sources/a.md', 'Synthetic');
  const output = path.join(base, 'cli-report.json');
  const args = [path.join(__dirname, 'maintain-wiki.cjs'), '--vault', vault, '--state-dir', stateDir, '--output', output, '--persist'];
  const result = require('node:child_process').spawnSync(process.execPath, args, { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr);
  const report = JSON.parse(fs.readFileSync(output));
  assert.equal(report.run.persisted, true);
  assert.equal(JSON.parse(result.stdout).counts.notes, 1);
  assert.equal(fs.readFileSync(note, 'utf8'), 'Synthetic');
  assert.deepEqual(fs.readdirSync(stateDir), ['maintenance-state.json']);
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(stateDir, 'maintenance-state.json'))).files, report.manifest.files);
  const second = require('node:child_process').spawnSync(process.execPath, args, { encoding: 'utf8' });
  assert.equal(second.status, 1);
  assert.match(second.stderr, /EEXIST/);
}));
test('raw modifications and deletions invalidate only explicit dependents and unsafe claims never read private targets', () => fixture(({ vault, stateDir, put }) => {
  const raw = put('raw/p.txt', 'Original');
  put('Sources/a.md', `---\nraw_path: raw/p.txt\nraw_sha256: ${hash('Original')}\n---\nSynthetic source`);
  put('Claims/c.json', JSON.stringify([claim('economy_wiki/raw/p.txt', hash('Original')), { ...claim('economy_wiki/raw/../private/p.txt', hash('secret')), id: 'unsafe' }]));
  api().persistWiki({ vault, stateDir });
  fs.appendFileSync(raw, ' modified');
  let r = api().auditWiki({ vault, stateDir });
  assert.ok(r.changes.changed.includes('economy_wiki/raw/p.txt'));
  assert.ok(r.changes.impacted.some(i => i.file.endsWith('/c.json')));
  assert.ok(r.issues.some(i => i.rule === 'raw-hash-mismatch'));
  fs.unlinkSync(raw);
  r = api().auditWiki({ vault, stateDir });
  assert.ok(r.changes.deleted.includes('economy_wiki/raw/p.txt'));
  assert.equal(r.claims.find(c => c.id === 'synthetic').state, 'missing');
}));
