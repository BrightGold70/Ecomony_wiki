  assert.throws(() => api().persistWiki({ vault, stateDir }), /busy/);
  assert.deepEqual(fs.readFileSync(path.join(stateDir, 'maintenance-state.json')), state);
  fs.unlinkSync(path.join(stateDir, 'maintenance.lock'));
