  api().cli(args);
  assert.equal(JSON.parse(fs.readFileSync(output)).run.persisted, false);
  assert.throws(() => api().cli([...args, '--persist']), /EEXIST/);
  assert.deepEqual(fs.readFileSync(path.join(stateDir, 'maintenance-state.json')), state);
  assert.throws(() => api().cli(['--vault', vault, '--state-dir', stateDir, '--output', path.join(vault, 'new.json')]), /overwrite/);
  fs.writeFileSync(path.join(stateDir, 'maintenance-state.json'), '{bad');
